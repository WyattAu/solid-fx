import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' })
await page.goto('http://localhost:4322/solid-fx/extras/fx/ui/poincaredisk/', { waitUntil: 'load' })
await page.waitForTimeout(4000)
const b = await page.locator('canvas').first().boundingBox()
await page.screenshot({ path: '/tmp/opencode/pd4-rest.png', clip: b })
await page.mouse.click(b.x + b.width / 2 - 60, b.y + b.height / 2)
await page.waitForTimeout(1500)
await page.screenshot({ path: '/tmp/opencode/pd4-clicked.png', clip: b })
await browser.close()
